// 入口只占河的这一段。首尾对齐设计定稿:第一颗 y=35%、最后一颗 y=84%。
// t = (y - 6) / 90(见 RIVER 表:y 从 0.06 线性排到 0.96)。
// ★ 中间三颗由 spreadT **等距**算出,不照抄定稿图里的 47/62/74 ——
//   那三个数是手填的,没有算法来源;定稿确认的是整张画面,不是这三个数。
//   代价:中间两颗与定稿差约 20px。**这类偏差要主动报出来**,不是"差异小就放过"。
//   换来的是「加一个入口,其余自动重排」不失效 —— 那个坑留给的是下一个改这里的人,
//   而那个人没法回来问我们。
const T_START = 0.3222;
const T_END = 0.8667;

// ★ 可见区间:银河容器比视口宽,左右会被裁掉一截,**裁多少由最极端的高宽比决定**
//   (手机 CSS 宽度只在 320–430 之间,但高宽比从 1.77 到 2.22;
//    2.22 那档每侧裁 16.2%)。这是设计层的常量,不是运行时视口 ——
//   按最狠那档定,任何手机上都看得见。
// ★ 素材换成 9:16 之后裁得少多了:320×568 几乎不裁,最狠的 2.22 长屏也只裁 10%
//   (上一版 2:3 的图要裁 16.2%)。可见区间因此宽松了,星星摆得开。
const VISIBLE = [0.10, 0.90];
// 容器宽高比(= 素材宽高比)。星星是正方形,所以「占容器高的百分比」换算成
// 「占容器宽的百分比」要除以这个数 —— 图越竖,同样高的星占宽越多。
const ASPECT = 900 / 1600;
// 标题/副标题那一块要占的横向空间(占容器宽的比例)。
// 取的是最长那条(「名字 · 主题 · 头像」≈121px / 533 ≈ 0.23)。
const TEXT_ROOM = 0.23;

// ★ 门厅不是功能索引。挂太多星,整条河会变成一串糖葫芦。
//   超过这个数的入口应该收进各自页面内部,而不是继续往河上插。
const MAX_GATES = 6;

// 超出上限的入口怎么办 —— **绝不静默丢掉**。
//
// ★ 上一版这里写的是 `GATES.slice(0, MAX_GATES)`:第七个入口会**无声消失**,
//   fork 的人加了功能、发现首屏没变化,却什么报错都没有。
//   这正是今天反复咬人的那个形状:**沉默被当成了成功**。
//   现在:多出来的照样返回,由调用方决定怎么安置,并且在控制台点名说出来。
function splitGates(gates, max = MAX_GATES) {
  const list = Array.isArray(gates) ? gates : [];
  const onRiver = list.slice(0, max);
  const overflow = list.slice(max);
  if (overflow.length && typeof console !== 'undefined' && console.warn) {
    console.warn(
      `[首屏] 河道最多挂 ${max} 个入口,这些没挂上去:`
      + overflow.map((g) => g.title || g.tab).join('、')
      + '。它们会收进「更多」那颗北斗;要让它们上河,得先把别的挪下来。',
    );
  }
  return { onRiver, overflow };
}

// 沿路径插值。t 落在两个采样点之间时线性混合 —— 采样够密(每 0.1 一个),
// 线性插值和曲线的差别在视觉上看不出来,却省掉一整套曲线求值。
function riverAt(t) {
  const u = Math.min(1, Math.max(0, Number(t) || 0));
  for (let i = 1; i < RIVER.length; i++) {
    const [t0, x0, y0, h0] = RIVER[i - 1];
    const [t1, x1, y1, h1] = RIVER[i];
    if (u <= t1 || i === RIVER.length - 1) {
      const k = t1 === t0 ? 0 : (u - t0) / (t1 - t0);
      return { x: x0 + (x1 - x0) * k, y: y0 + (y1 - y0) * k, half: h0 + (h1 - h0) * k };
    }
  }
  const [, x, y, h] = RIVER[RIVER.length - 1];
  return { x, y, half: h };
}

// 把入口摊在 [T_START, T_END] 上。**这是「加一个入口,其余自动重排」的全部机制** ——
// t 由序号算,不由人填,所以数组一变,每一颗的位置都跟着变。
function spreadT(n, i) {
  if (n <= 0) return T_START;
  if (n === 1) return (T_START + T_END) / 2;
  return T_START + (T_END - T_START) * (i / (n - 1));
}

// 由入口表算出每颗星的落点。
//
// ★ 星心**落在河心上**(2026-08-11 起)。上一版是"挂在河边、偏移 = 半宽 + 0.55 星半宽",
//   连同那句「沿着路走 ≠ 站在路当中」一起作废 —— 理由见 layoutGates 内部的规则变更说明:
//   背景图换成 newbg 之后河收窄成细带子,原规则的前提没了。
//
// ★ size 是「占容器高的百分比」。它现在**不再影响落点**(x 恒等于河心),
//   只参与"文字塞不塞得下"的判断。
// 文字块要占多宽(占容器宽的比例)。按字数估,不用一个"最长的那条"去卡所有人 ——
// 「名字 · 主题 · 头像」要 0.23,而「珍藏回忆」只要 0.09,一刀切会把本来放得下的挤掉。
// 基准宽度取最紧那档手机的容器宽(533px):标题 ~15px/字、副标题 ~11px/字。
const REF_W = 450;   // 最紧那档手机(360×800)的容器宽 = 800 × 0.5625

// ★★ 这个上限必须和 styles.css 里 `.sg-text{max-width:38vw}` 是同一个数。
//    它们是**同一件事的两处声明**:文字实际能占多宽。
//    以前只有 CSS 那一处有上限,几何层这边按字数无限增长 —— 于是用户起个长名字时,
//    几何层算出"文字要 0.42 容器宽,两侧都放不下",直接退到最后的兜底,
//    而 CSS 其实早就把它省略号截到 0.31 了,**本来放得下**。
//    两层对同一个量各说各话,结果是谁都没算错,但合起来把标签甩出了屏幕。
//    (38vw 换算成容器宽的比例在 0.30~0.38 之间浮动 —— 取上界偏保守,
//     宁可多留一点空间,也不要算出"放不下"这种假结论。)
const MAX_TEXT_ROOM = 0.38;

function textRoomFor(g) {
  const title = String(g.title || '');
  const hint = String(g.hintText || '');
  const want = Math.max(title.length * 15, hint.length * 11) / REF_W;
  return Math.min(want, MAX_TEXT_ROOM);
}

// 在某一侧,星心能放的**最外**位置(再往外文字就出界了)。
//
// ★ 这里原本写的是 `starHalf * 2`,**把星星的半宽算了两遍**。
//   真实几何(390 屏实测):星心 207、半宽 55、文字右缘 147 —— 星心到文字之间
//   只隔着**一个**半宽 + `.3rem` 的缝(CSS: `.sg-left .sg-text{right:calc(100% + .3rem)}`)。
//   多留一个半宽(0.116 容器宽)的后果不是"更安全",而是几何层**误判成放不下**:
//   长名字那档实测只差 1px 就能放下,公式却算出 -0.095,于是直接退到最后的兜底,
//   而兜底不保证文字在屏内 —— **一个偏保守的公式,反而制造了它想避免的故障。**
const STAR_TEXT_GAP = 0.012;   // .3rem ≈ 4.8px,占容器宽(≈475px)约 1.2%

function maxOffsetOn(side, center, starHalf, textRoom) {
  const reserve = starHalf + STAR_TEXT_GAP + textRoom;
  return side === 'right'
    ? (VISIBLE[1] - reserve) - center
    : center - (VISIBLE[0] + reserve);
}

function layoutGates(gates) {
  const list = Array.isArray(gates) ? gates : [];
  const n = list.length;
  return list.map((g, i) => {
    const t = spreadT(n, i);
    const p = riverAt(t);
    const starHalf = (Number(g.size) || 0) / 100 / ASPECT / 2;   // 见 ASPECT 注释
    const room = textRoomFor(g);
    const want = g.side === 'left' ? 'left' : 'right';

    // ★★ 2026-08-11:落点规则由 **river-edge 改为 river-center**。
    //    星心直接落在河心上,不再"挂在河边"。
    //    原因不是审美偏好,是背景图换了:galaxy-river 的河宽,骑上去会把它截断;
    //    newbg 的河收窄成细带子(y=35 那股只占全行 48%、宽 3.0%),
    //    细带子上坐一颗星和宽河上坐一颗星不是一回事。**规则的前提没了,规则跟着走。**
    //    视觉基准:设计定稿那版画面。
    //
    // ★ 连带后果:**"让位"这个机制整个消失了,不是重写。**
    //    原来可以让的是「离河的距离」;星心落河心之后,推的量已经是 0,
    //    **没有任何方向可以退** —— 退就是离开河心,等于退回旧设计。
    //    所以下面不再有 pick/relaxed 两级,也不再有 floor 这道准入门槛:
    //    ★ floor 必须和 wish 一起归零。只把 wish 设 0 而留着 `cap < floor` 的话,
    //      会变成「明明只要偏移 0 就够,却仍然要求 cap ≥ 河道半宽才准入」——
    //      把放得下的判成放不下,又是一个"偏保守的门槛亲手制造它要防的降级"。

    // 星心 = 河心。side 现在**只决定文字朝哪边展开**,不再影响星星的位置。
    const fits = (side) => maxOffsetOn(side, p.x, starHalf, room) >= 0;
    const other = want === 'left' ? 'right' : 'left';
    // 首选侧塞得下文字就用它;塞不下翻到另一侧;两侧都塞不下就保持首选,
    // 由 CSS 的 max-width + 省略号收尾(几何层此时确实没牌可打了 —— 这是甲案的已知代价)。
    const side = fits(want) ? want : (fits(other) ? other : want);

    // ★★ 星心落河心,**但星星整个要留在可见区里**。河在 y≈72% 那段跑到 84%,
    //    图标半宽 8.6% —— 右缘到 92.6%,超出可见区 2.6%,真机四档屏宽全部被裁。
    //    ⇒ 这不是"骑不骑河"的例外,是**边界条件**:河可以跑到画布边上,星星不能跟出去。
    //    定稿图里控制台那颗 84.3→82.5 是同一件事,标的是 `[clamped]` 不是 `[eyeballed]` ——
    //    算出来的让步,不是手抖。
    //
    // ★ 我把三级让位塌成一级时,连这条 clamp 一起删了(它原来藏在旧 ④ 兜底里)。
    //   删掉之后 8px 落点门槛**没报** —— 因为偏差 6.9px 刚好小于门槛 8px。
    //   **一个真缺陷藏进了容差里**:门槛该吸收噪声,不该吸收系统性偏差。
    const lo = VISIBLE[0] + starHalf;
    const hi = VISIBLE[1] - starHalf;
    const chosen = { side, x: lo > hi ? (VISIBLE[0] + VISIBLE[1]) / 2 : Math.min(hi, Math.max(lo, p.x)) };
    return { ...g, t, side: chosen.side, x: chosen.x * 100, y: p.y * 100 };
  });
}

